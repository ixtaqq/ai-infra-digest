-- Persist alert claims so repeated or overlapping digest runs cannot send the
-- same high-impact article to the same user more than once.
CREATE TABLE public.alert_delivery_log (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  chat_id BIGINT NOT NULL,
  content_hash TEXT NOT NULL CHECK (content_hash ~ '^[0-9a-f]{64}$'),
  status TEXT NOT NULL CHECK (status IN ('pending', 'success', 'failed')),
  details TEXT,
  claimed_at TIMESTAMPTZ,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UNIQUE (chat_id, content_hash)
);

CREATE INDEX idx_alert_delivery_claim_state
  ON public.alert_delivery_log(status, claimed_at)
  WHERE status = 'pending';

CREATE INDEX idx_alert_delivery_created_at
  ON public.alert_delivery_log(created_at);

ALTER TABLE public.alert_delivery_log ENABLE ROW LEVEL SECURITY;

CREATE POLICY "service_role_access"
  ON public.alert_delivery_log
  FOR ALL
  TO service_role
  USING (true)
  WITH CHECK (true);

REVOKE ALL ON TABLE public.alert_delivery_log FROM PUBLIC, anon, authenticated;
GRANT ALL ON TABLE public.alert_delivery_log TO service_role;
GRANT USAGE, SELECT ON SEQUENCE public.alert_delivery_log_id_seq TO service_role;

CREATE OR REPLACE FUNCTION public.claim_high_impact_alert(
  p_chat_id BIGINT,
  p_content_hash TEXT,
  p_stale_after_seconds INTEGER DEFAULT 1800
)
RETURNS BOOLEAN
LANGUAGE plpgsql
SECURITY INVOKER
SET search_path = ''
AS $$
DECLARE
  did_claim BOOLEAN;
BEGIN
  IF p_chat_id IS NULL OR p_content_hash !~ '^[0-9a-f]{64}$' THEN
    RETURN FALSE;
  END IF;

  INSERT INTO public.alert_delivery_log (
    chat_id,
    content_hash,
    status,
    details,
    claimed_at
  )
  VALUES (
    p_chat_id,
    p_content_hash,
    'pending',
    'claimed - send in progress',
    CURRENT_TIMESTAMP
  )
  ON CONFLICT (chat_id, content_hash) DO UPDATE
  SET
    status = 'pending',
    details = 'claimed - send in progress',
    claimed_at = CURRENT_TIMESTAMP,
    updated_at = CURRENT_TIMESTAMP
  WHERE public.alert_delivery_log.status = 'failed'
     OR (
       public.alert_delivery_log.status = 'pending'
       AND (
         public.alert_delivery_log.claimed_at IS NULL
         OR public.alert_delivery_log.claimed_at < CURRENT_TIMESTAMP -
           GREATEST(p_stale_after_seconds, 1) * INTERVAL '1 second'
       )
     )
  RETURNING TRUE INTO did_claim;

  RETURN COALESCE(did_claim, FALSE);
END;
$$;

REVOKE EXECUTE ON FUNCTION public.claim_high_impact_alert(BIGINT, TEXT, INTEGER)
  FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.claim_high_impact_alert(BIGINT, TEXT, INTEGER)
  TO service_role;

-- Private product events support onboarding, activation, retention, and
-- delivery-lateness analysis without exposing Telegram identities publicly.
CREATE TABLE public.product_events (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  event_name TEXT NOT NULL CHECK (
    event_name IN (
      'onboarding_started',
      'onboarding_completed',
      'delivery_succeeded',
      'delivery_failed'
    )
  ),
  chat_id BIGINT NOT NULL,
  properties JSONB NOT NULL DEFAULT '{}'::jsonb,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_product_events_name_created
  ON public.product_events(event_name, created_at DESC);

CREATE INDEX idx_product_events_chat_created
  ON public.product_events(chat_id, created_at DESC);

ALTER TABLE public.product_events ENABLE ROW LEVEL SECURITY;

