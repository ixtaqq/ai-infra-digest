-- Search through the Data API with the same expression used by idx_articles_fts.
-- SECURITY INVOKER preserves the articles table's public-read RLS boundary.
GRANT SELECT ON TABLE public.articles TO anon, authenticated;

CREATE OR REPLACE FUNCTION public.search_articles(
  p_query TEXT,
  p_limit INTEGER DEFAULT 20,
  p_offset INTEGER DEFAULT 0
)
RETURNS JSONB
LANGUAGE sql
STABLE
SECURITY INVOKER
SET search_path = ''
AS $$
  WITH search_query AS (
    SELECT websearch_to_tsquery('english', LEFT(COALESCE(p_query, ''), 80)) AS value
  ),
  matched AS (
    SELECT
      a.*,
      ts_rank(
        to_tsvector(
          'english',
          COALESCE(a.title, '') || ' ' ||
          COALESCE(a.summary, '') || ' ' ||
          COALESCE(a.source, '') || ' ' ||
          COALESCE(a.category, '')
        ),
        q.value
      ) AS search_rank
    FROM public.articles AS a
    CROSS JOIN search_query AS q
    WHERE numnode(q.value) > 0
      AND to_tsvector(
        'english',
        COALESCE(a.title, '') || ' ' ||
        COALESCE(a.summary, '') || ' ' ||
        COALESCE(a.source, '') || ' ' ||
        COALESCE(a.category, '')
      ) @@ q.value
  ),
  page AS (
    SELECT
      id,
      title,
      url,
      source,
      impact,
      impact_score,
      effective_score,
      ranking_explanation,
      is_sec_filing,
      category,
      affected_stocks,
      summary,
      reason,
      bear_case,
      thumbs_up,
      thumbs_down,
      created_at
    FROM matched
    ORDER BY search_rank DESC, impact_score DESC NULLS LAST, created_at DESC, id DESC
    LIMIT LEAST(GREATEST(COALESCE(p_limit, 20), 1), 100)
    OFFSET GREATEST(COALESCE(p_offset, 0), 0)
  )
  SELECT jsonb_build_object(
    'articles', COALESCE((SELECT jsonb_agg(to_jsonb(page)) FROM page), '[]'::jsonb),
    'total', (SELECT COUNT(*) FROM matched)
  );
$$;

REVOKE EXECUTE ON FUNCTION public.search_articles(TEXT, INTEGER, INTEGER) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.search_articles(TEXT, INTEGER, INTEGER)
  TO anon, authenticated, service_role;

CREATE OR REPLACE FUNCTION public.cleanup_old_data()
RETURNS void
LANGUAGE plpgsql
SECURITY INVOKER
SET search_path = ''
AS $$
DECLARE
  deleted_articles INT;
  deleted_pipeline INT;
  deleted_ai_usage INT;
  deleted_delivery_log INT;
  deleted_alert_log INT;
  deleted_product_events INT;
  deleted_capex INT;
BEGIN
  DELETE FROM public.articles
  WHERE created_at < CURRENT_TIMESTAMP - INTERVAL '90 days';
  GET DIAGNOSTICS deleted_articles = ROW_COUNT;

  DELETE FROM public.pipeline_health
  WHERE created_at < CURRENT_TIMESTAMP - INTERVAL '30 days';
  GET DIAGNOSTICS deleted_pipeline = ROW_COUNT;

  DELETE FROM public.ai_usage
  WHERE created_at < CURRENT_TIMESTAMP - INTERVAL '90 days';
  GET DIAGNOSTICS deleted_ai_usage = ROW_COUNT;

  DELETE FROM public.user_delivery_log
  WHERE created_at < CURRENT_TIMESTAMP - INTERVAL '90 days';
  GET DIAGNOSTICS deleted_delivery_log = ROW_COUNT;

  DELETE FROM public.alert_delivery_log
  WHERE created_at < CURRENT_TIMESTAMP - INTERVAL '90 days';
  GET DIAGNOSTICS deleted_alert_log = ROW_COUNT;

  DELETE FROM public.product_events
  WHERE created_at < CURRENT_TIMESTAMP - INTERVAL '180 days';
  GET DIAGNOSTICS deleted_product_events = ROW_COUNT;

  DELETE FROM public.capex_tracking
  WHERE created_at < CURRENT_TIMESTAMP - INTERVAL '365 days';
  GET DIAGNOSTICS deleted_capex = ROW_COUNT;

  RAISE NOTICE 'Retention cleanup: articles=%, pipeline_health=%, ai_usage=%, delivery_log=%, alert_log=%, product_events=%, capex=%',
    deleted_articles,
    deleted_pipeline,
    deleted_ai_usage,
    deleted_delivery_log,
    deleted_alert_log,
    deleted_product_events,
    deleted_capex;
END;
$$;
