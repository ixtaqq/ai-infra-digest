-- A function call is one transaction in Postgres. Any failed delete rolls the
-- entire privacy operation back instead of leaving a partially erased user.
CREATE OR REPLACE FUNCTION public.delete_user_data(p_chat_id BIGINT)
RETURNS BOOLEAN
LANGUAGE plpgsql
SECURITY INVOKER
SET search_path = ''
AS $$
BEGIN
  IF p_chat_id IS NULL OR p_chat_id <= 0 THEN
    RETURN FALSE;
  END IF;

  UPDATE public.user_preferences
  SET is_active = FALSE, updated_at = CURRENT_TIMESTAMP
  WHERE chat_id = p_chat_id;

  DELETE FROM public.user_delivery_log WHERE chat_id = p_chat_id;
  DELETE FROM public.alert_delivery_log WHERE chat_id = p_chat_id;
  DELETE FROM public.product_events WHERE chat_id = p_chat_id;
  DELETE FROM public.price_watches WHERE chat_id = p_chat_id;
  DELETE FROM public.command_usage WHERE chat_id = p_chat_id;
  DELETE FROM public.article_validations WHERE chat_id = p_chat_id;
  DELETE FROM public.delivery_email_verifications WHERE chat_id = p_chat_id;
  DELETE FROM public.user_preferences WHERE chat_id = p_chat_id;

  RETURN TRUE;
END;
$$;

REVOKE EXECUTE ON FUNCTION public.delete_user_data(BIGINT)
  FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.delete_user_data(BIGINT)
  TO service_role;

CREATE OR REPLACE FUNCTION public.verify_delivery_email(
  p_chat_id BIGINT,
  p_code_hash TEXT
)
RETURNS BOOLEAN
LANGUAGE plpgsql
SECURITY INVOKER
SET search_path = ''
AS $$
DECLARE
  pending public.delivery_email_verifications%ROWTYPE;
BEGIN
  IF p_chat_id IS NULL OR p_chat_id <= 0 OR p_code_hash IS NULL
     OR p_code_hash !~ '^[0-9a-f]{64}$' THEN
    RETURN FALSE;
  END IF;

  SELECT * INTO pending
  FROM public.delivery_email_verifications
  WHERE chat_id = p_chat_id
  FOR UPDATE;

  IF NOT FOUND THEN
    RETURN FALSE;
  END IF;

  IF pending.expires_at <= CURRENT_TIMESTAMP OR pending.attempts >= 5 THEN
    DELETE FROM public.delivery_email_verifications WHERE chat_id = p_chat_id;
    RETURN FALSE;
  END IF;

  UPDATE public.delivery_email_verifications
  SET attempts = attempts + 1, updated_at = CURRENT_TIMESTAMP
  WHERE chat_id = p_chat_id;

  IF pending.code_hash <> p_code_hash THEN
    RETURN FALSE;
  END IF;

  INSERT INTO public.user_preferences (chat_id, delivery_email)
  VALUES (p_chat_id, pending.email)
  ON CONFLICT (chat_id) DO UPDATE
  SET delivery_email = EXCLUDED.delivery_email,
      updated_at = CURRENT_TIMESTAMP;

  DELETE FROM public.delivery_email_verifications WHERE chat_id = p_chat_id;
  RETURN TRUE;
END;
$$;

REVOKE EXECUTE ON FUNCTION public.verify_delivery_email(BIGINT, TEXT)
  FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.verify_delivery_email(BIGINT, TEXT)
  TO service_role;

