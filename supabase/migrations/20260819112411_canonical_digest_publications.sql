-- One immutable editorial edition per calendar date. Scheduled delivery reads
-- these rows and never invokes the collection or AI pipeline.
CREATE TABLE public.digest_publications (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  publication_date DATE NOT NULL UNIQUE,
  schema_version INTEGER NOT NULL CHECK (schema_version > 0),
  payload JSONB NOT NULL CHECK (jsonb_typeof(payload) = 'object'),
  article_ids JSONB NOT NULL DEFAULT '{}'::jsonb CHECK (jsonb_typeof(article_ids) = 'object'),
  published_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_digest_publications_date
  ON public.digest_publications(publication_date DESC);

ALTER TABLE public.digest_publications ENABLE ROW LEVEL SECURITY;

CREATE POLICY "service_role_select"
  ON public.digest_publications
  FOR SELECT
  TO service_role
  USING (true);

CREATE POLICY "service_role_insert"
  ON public.digest_publications
  FOR INSERT
  TO service_role
  WITH CHECK (true);

REVOKE ALL ON TABLE public.digest_publications FROM PUBLIC, anon, authenticated;
GRANT SELECT, INSERT ON TABLE public.digest_publications TO service_role;
GRANT USAGE, SELECT ON SEQUENCE public.digest_publications_id_seq TO service_role;

